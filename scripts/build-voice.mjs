// Rebuilds the in-game voice pack from the owner's source WAVs.
//   node scripts/build-voice.mjs <folder with manifest.json + audio/*.wav> [outDir=public/audio/voice]
// Needs ffmpeg (libmp3lame) on the PATH. Writes one small mono mp3 per line plus src/fx/voice-data.js (text, speaker, duration, categories).
// The source WAVs stay with the owner (7.4 MB zip); only the 22 kHz mp3s ship, so the game never downloads more than the lines an operation needs.
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const src = resolve(process.argv[2] ?? '');
const out = resolve(process.argv[3] ?? 'public/audio/voice');
if (!process.argv[2]) { console.error('usage: node scripts/build-voice.mjs <voice pack folder> [outDir]'); process.exit(1); }
const manifest = JSON.parse(readFileSync(join(src, 'manifest.json'), 'utf8'));
mkdirSync(out, { recursive: true });

const VOICE = {}, CATEGORIES = {};
let bytes = 0;
for (const b of manifest.barks) {
  const id = b.id;
  const mp3 = join(out, `${id}.mp3`);
  const r = spawnSync('ffmpeg', ['-y', '-v', 'error', '-i', join(src, b.file), '-ac', '1', '-ar', '22050', '-c:a', 'libmp3lame', '-b:a', '32k', mp3]);
  if (r.status !== 0) { console.error(`ffmpeg failed for ${id}: ${r.stderr}`); process.exit(1); }
  bytes += statSync(mp3).size;
  VOICE[id] = { s: b.speaker, t: b.text, d: +b.duration.toFixed(2) };
  const cat = id.split('_')[0];                                      // onKill_dust -> onKill
  (CATEGORIES[cat] ??= []).push(id);
}
const js = `// GENERATED by scripts/build-voice.mjs from the owner's voice pack (${manifest.pack}). Do not edit by hand.
// id -> { s: speaker, t: subtitle text, d: seconds }; categories group the variants of one line (picked round-robin by the bark director).
export const VOICE = ${JSON.stringify(VOICE, null, 1)};
export const VOICE_CATEGORIES = ${JSON.stringify(CATEGORIES, null, 1)};
`;
writeFileSync(resolve('src/fx/voice-data.js'), js);
console.log(`${Object.keys(VOICE).length} lines, ${Object.keys(CATEGORIES).length} categories, ${(bytes / 1024).toFixed(0)} KB of mp3 -> ${out}`);
